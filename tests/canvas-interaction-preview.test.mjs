import test from 'node:test';
import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { JSDOM, VirtualConsole } from 'jsdom';
import { readFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { installMatchMedia } from './helpers/media-query.mjs';

test('component interaction preview supports controls and replay without moving or editing the document', async t => {
  const errors=[],virtualConsole=new VirtualConsole();
  virtualConsole.on('error',(...args)=>errors.push(args.join(' ')));
  virtualConsole.on('jsdomError',error=>errors.push(error.message));
  const dom=new JSDOM('<div id="root"></div>',{url:'https://canvas-preview.test',runScripts:'dangerously',pretendToBeVisual:true,virtualConsole});
  const {window}=dom;
  t.after(()=>{window.unmount?.();window.close();});
  installMatchMedia(window,{reducedMotion:true});
  window.ResizeObserver=class{observe(){}unobserve(){}disconnect(){}};
  window.HTMLElement.prototype.scrollIntoView=()=>{};
  const captures=new Set();
  window.HTMLElement.prototype.setPointerCapture=id=>captures.add(id);
  window.HTMLElement.prototype.hasPointerCapture=id=>captures.has(id);
  window.HTMLElement.prototype.releasePointerCapture=id=>captures.delete(id);
  const bundle=await build({
    stdin:{contents:`
      import {useState} from 'react';
      import {createRoot} from 'react-dom/client';
      import {flushSync} from 'react-dom';
      import {DndContext} from '@dnd-kit/core';
      import {FreeCanvas} from './src/components/FreeCanvas';
      import {FreePage} from './src/components/PageRenderer';
      import {createDocument,createBlock} from './src/model';
      const page={...createDocument(true),blocks:[{...createBlock('switch'),id:'switch',frame:{x:16,y:16,width:420,height:120}},{...createBlock('text'),id:'front',frame:{x:16,y:16,width:420,height:120}}]};
      window.changes=[];
      const change=(...args)=>window.changes.push(args);
      const noop=()=>{};
      function Fixture(){const [selected,setSelected]=useState('switch');return <><DndContext><FreeCanvas document={page} selected={selected} onSelect={setSelected} onFrameChange={change} onBlockChange={change} onCanvasSizeChange={change} onPageMarginChange={change} onPageSettings={noop} onDelete={change} onDuplicate={change} onInspect={noop} onCreateVariable={noop} onAlign={change} onFillWidth={change} onLayerChange={change} isDragging={false} device="desktop"/></DndContext><FreePage document={page}/></>;}
      const root=createRoot(document.getElementById('root'));
      window.perform=fn=>flushSync(fn);window.unmount=()=>flushSync(()=>root.unmount());
      window.perform(()=>root.render(<Fixture/>));
    `,loader:'jsx',resolveDir:fileURLToPath(new URL('../',import.meta.url))},bundle:true,write:false,format:'iife',jsx:'automatic',external:['shiki'],loader:{'.css':'empty'},define:{'process.env.NODE_ENV':'"development"'},logLevel:'silent',
    plugins:[{name:'raw',setup(build){build.onResolve({filter:/\?raw$/},args=>({path:resolve(args.resolveDir,args.path.slice(0,-4)),namespace:'raw'}));build.onLoad({filter:/.*/,namespace:'raw'},async args=>({contents:await readFile(args.path,'utf8'),loader:'text',resolveDir:dirname(args.path)}));}}],
  });
  window.eval(bundle.outputFiles[0].text);
  const doc=window.document,frame=()=>doc.querySelector('[data-block-id="switch"]'),control=()=>frame().querySelector('[role="switch"]');
  const key=(target,key)=>window.perform(()=>target.dispatchEvent(new window.KeyboardEvent('keydown',{key,bubbles:true,cancelable:true})));
  assert.equal(frame().style.zIndex,'1','selecting the bottom component must not raise its content above other components');
  assert.deepEqual([...doc.querySelectorAll('.page-free-frame')].map(element=>element.style.zIndex),['1','2'],'preview uses the same explicit stacking order');
  const overlay=doc.querySelector('[data-selection-for="switch"]');
  assert.equal(overlay.parentElement,frame().parentElement,'selection controls live outside the component stacking context');
  assert.equal(overlay.style.zIndex,'3');
  assert.match(overlay.querySelector('.free-canvas-measure').textContent, /420 × 120缩放 100%/);
  assert.equal(control().disabled,true);
  key(frame(),'Enter');
  assert.equal(frame().getAttribute('data-canvas-interactive'),'true');
  assert.equal(control().disabled,false);
  assert.equal(frame().querySelector('[inert]'),null);
  assert.equal(doc.querySelector('.free-canvas-selection-overlay .free-canvas-resize-handle'),null);
  window.perform(()=>control().click());
  assert.equal(control().getAttribute('aria-checked'),'true');
  const pointer=new window.MouseEvent('pointerdown',{button:0,bubbles:true,cancelable:true,clientX:40,clientY:40});
  Object.defineProperty(pointer,'pointerId',{value:1});
  window.perform(()=>control().dispatchEvent(pointer));
  assert.equal(captures.size,0,'operating the switch must not start a canvas drag');
  let escapedDelete=0;window.addEventListener('keydown',e=>{if(e.key==='Delete')escapedDelete++;});
  key(control(),'Delete');assert.equal(escapedDelete,0);
  window.perform(()=>doc.querySelector('[aria-label="重播开关动效"]').click());
  assert.equal(control().getAttribute('aria-checked'),'false','replay resets only transient component state');
  key(control(),'Escape');
  assert.equal(frame().hasAttribute('data-canvas-interactive'),false);
  assert.equal(control().disabled,true);
  assert.equal(doc.activeElement,frame());
  assert.equal(doc.querySelectorAll('.free-canvas-selection-overlay .free-canvas-resize-handle').length,8);
  window.perform(()=>doc.querySelector('.free-canvas-frame[data-block-id="front"]').focus());
  assert.equal(frame().style.zIndex,'1');
  assert.equal(doc.querySelector('.free-canvas-frame[data-block-id="front"]').style.zIndex,'2');
  assert.deepEqual(Array.from(window.changes),[]);
  const sendPointer = (target,type,x,y) => window.perform(() => {
    const event = new window.MouseEvent(type,{button:0,bubbles:true,cancelable:true,clientX:x,clientY:y});
    Object.defineProperty(event,'pointerId',{value:2});
    target.dispatchEvent(event);
  });
  const handle = doc.querySelector('.free-canvas-resize-handle--e');
  sendPointer(handle,'pointerdown',40,40);
  sendPointer(handle,'pointermove',50,40);
  sendPointer(handle,'pointerup',50,40);
  assert.equal(window.changes.length,1,'resize controls still commit through the separate selection overlay');
  assert.equal(window.changes[0][0],'front');
  assert.ok(window.changes[0][1].width>420);
  assert.equal(captures.size,0);
  const bar = doc.querySelector('.free-canvas-selection-bar');
  sendPointer(bar,'pointerdown',40,40);
  sendPointer(bar,'pointermove',50,50);
  sendPointer(bar,'pointerup',50,50);
  assert.equal(window.changes.length,2,'the selection toolbar still drags its component');
  assert.equal(window.changes[1][0],'front');
  assert.ok(window.changes[1][1].x>16);
  assert.equal(captures.size,0);
  assert.deepEqual(errors,[]);
});
