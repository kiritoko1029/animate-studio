import { interactionSource } from './interaction-source.ts';
import type { PageDocument } from '../../model.ts';
import { createPageTree } from './blocks.ts';
import { escapeHtml, js, render, type Format } from './nodes.ts';
import { browserHelpers, htmlAttributeHelper } from './runtime.ts';

export type ExportResources = { pageCss: string; libraryCss: string; portableCss: string; catalogCss?: string; assets?: Record<string, string>; previewToken?: string };
export type CodeExport = { filename: string; mime: string; content: string };
export type { Format } from './nodes.ts';

export function generateCode(document: PageDocument, format: Format, resources: ExportResources): CodeExport {
  const interaction = interactionSource(document);
  const { tree, state, width, height } = createPageTree(document, resources.assets);
  const { markup, updates, listeners } = render(tree, format);
  // Existing page styles are plain CSS. Renaming class selectors avoids coupling exports to the editor or host app.
  const css = `${resources.portableCss}\n${resources.pageCss.replace(/\.page-/g, '.as-page-')}\n${resources.libraryCss.replace(/\.page-/g, '.as-page-')}\n${resources.catalogCss ?? ''}`;
  const notes = `Generated by Animate Studio.\nFixed design canvas: ${width} × ${height}; scales down to its container without mobile reflow.\nPage variables, bindings, actions and scripts are included. Business APIs must be connected separately.\nExternal/custom image URLs remain references; the built-in landscape is embedded.\nKeep the JSON export separately if you want to edit this page in Animate Studio again.`;
  if (format === 'html') {
    const name = document.name.replace(/[\\/:*?"<>|\u0000-\u001f\u007f]/g, '-').replace(/[. ]+$/g, '').slice(0, 100) || 'page';
    return { filename: `${name}.html`, mime: 'text/html;charset=utf-8', content: `<!doctype html>
<html lang="zh-CN">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${escapeHtml(document.name)}</title>
  <style>body { margin: 0; }${resources.previewToken ? '\n/* The editor owns preview scrolling; nested scrollbars would change the canvas scale. */\nhtml, body { overflow: hidden; }' : ''}\n${css}</style>
</head>
<body>
<!-- ${notes} -->
${markup}
<script>
(() => {
  const root = document.querySelector('.as-export');
  const uid = 'as-export';
  const state = ${js(state)};
  const interactionConfig = ${interaction.config};
  let data = ${interaction.initial};
  const logic = (${interaction.factory})(interactionConfig, {
    storageKey: ${interaction.storageKey},
    onState(next) { data = next; sync(); ${resources.previewToken ? `parent.postMessage({ type: 'as-state', token: ${js(resources.previewToken)}, state: data }, '*');` : ''} },
    onLog(entry) { ${resources.previewToken ? `parent.postMessage({ type: 'as-log', token: ${js(resources.previewToken)}, entry }, '*');` : `if (entry.level === 'error') showNotice(root, entry.message);`} },
    onNotify: message => ${resources.previewToken ? `parent.postMessage({ type: 'as-notify', token: ${js(resources.previewToken)}, message }, '*')` : 'showNotice(root, message)'}, onNavigate: url => followLink(root, url),
  });
  ${interaction.helpers}
  ${resources.previewToken ? `window.addEventListener('message', async event => {
    if (event.source !== parent || event.data?.token !== ${js(resources.previewToken)}) return;
    if (event.data.type === 'as-viewport' && Number.isFinite(event.data.top) && Number.isFinite(event.data.height)) {
      root.style.setProperty('--catalog-vtop', Math.max(0, event.data.top) + 'px');
      root.style.setProperty('--catalog-vheight', Math.max(80, event.data.height) + 'px');
      root.querySelectorAll('[data-catalog-scroll]').forEach(bar => { bar.value = Math.max(0, Math.min(100, Number(event.data.progress) || 0)); });
    }
    if (event.data.type === 'as-reset') logic.reset();
    if (event.data.type === 'as-run') { try { await logic.runScript(event.data.id); } catch (error) { parent.postMessage({type:'as-log', token:${js(resources.previewToken)}, entry:{level:'error', message:error.message, time:Date.now()}}, '*'); } }
  });
  parent.postMessage({type:'as-ready', token:${js(resources.previewToken)}, state:data}, '*');` : ''}
  const nodes = {};
  for (const node of [root, ...root.querySelectorAll('[data-as-node]')]) nodes[node.dataset.asNode] = node;
  ${htmlAttributeHelper}
  function sync() {
    ${updates.join('\n    ')}
  }
  function update(key, value) { state[key] = value; sync(); }
  ${listeners.join('\n  ')}
  ${browserHelpers}
  logic.activate();
  sync();
  const dispose = mountPage(root, ${width}, ${height});
  window.addEventListener('pagehide', () => { logic.dispose(); dispose(); }, {once:true});
})();
</script>
</body>
</html>\n` };
  }
  if (format === 'vue') {
    return { filename: 'GeneratedPage.vue', mime: 'text/plain;charset=utf-8', content: `<!--
${notes}
Requires Vue 3.5+ with Single File Component support. No additional UI or animation packages.
Usage: import GeneratedPage from './GeneratedPage.vue'; then render <GeneratedPage />.
-->
<script setup>
import { reactive, ref, useId, onMounted, onUnmounted } from 'vue';

const uid = useId();
const rootRef = ref(null);
const state = reactive(${js(state)});
const interactionConfig = ${interaction.config};
const data = reactive(${interaction.initial});
const logic = (${interaction.factory})(interactionConfig, {
  storageKey: ${interaction.storageKey},
  onState(next) { Object.assign(data, next); },
  onLog(entry) { if (entry.level === 'error') showNotice(rootRef.value, entry.message); },
  onNotify: message => showNotice(rootRef.value, message), onNavigate: url => followLink(rootRef.value, url),
});
${interaction.helpers}
function update(key, value) { state[key] = value; }
${browserHelpers}
let dispose;
onMounted(() => { logic.activate(); dispose = mountPage(rootRef.value, ${width}, ${height}); });
onUnmounted(() => { dispose?.(); logic.dispose(); });
</script>

<template>
${markup}
</template>

<style scoped>
${css}
</style>\n` };
  }
  return { filename: 'GeneratedPage.jsx', mime: 'text/plain;charset=utf-8', content: `'use client';
/*
${notes}
Requires React 18+ with JSX support. No additional UI or animation packages.
Usage: import GeneratedPage from './GeneratedPage.jsx'; then render <GeneratedPage />.
*/
import { useEffect, useId, useRef, useState } from 'react';

const styles = ${js(css)};
${browserHelpers}

export default function GeneratedPage() {
  const uid = useId();
  const rootRef = useRef(null);
  const [state, setState] = useState(${js(state)});
  const interactionConfig = ${interaction.config};
  const [data, setData] = useState(${interaction.initial});
  const [logic] = useState(() => (${interaction.factory})(interactionConfig, {
    storageKey: ${interaction.storageKey},
    onState: setData,
    onLog(entry) { if (entry.level === 'error') showNotice(rootRef.current, entry.message); },
    onNotify: message => showNotice(rootRef.current, message), onNavigate: url => followLink(rootRef.current, url),
  }));
  ${interaction.helpers}
  function update(key, value) { setState(previous => ({ ...previous, [key]: value })); }
  useEffect(() => { logic.activate(); const dispose = mountPage(rootRef.current, ${width}, ${height}); return () => { dispose(); logic.dispose(); }; }, [logic]);
  return (
    <>
      <style>{styles}</style>
      ${markup}
    </>
  );
}\n` };
}
